"""PhotoDNA Edge Hash generation (wrapper around Microsoft's EdgeHash SDK).

Microsoft's PhotoDNA Cloud Service does NOT accept raw images: requests to
`MatchHash` must carry PhotoDNA Edge Hashes generated locally with their
EdgeHashGeneration SDK. The hashes are irreversible and ~1KB, so no imagery
ever leaves this server for the photodna provider -- a privacy upgrade over
URL-submission providers.

The SDK itself is licensed/non-redistributable and is NOT committed to git
(it is gitignored). It was downloaded 2026-11-18 from Microsoft's share
(PhotoDNA.EdgeHashGeneration-1.05.009, zip SHA256 verified against the
published value) and lives wherever PHOTODNA_SDK_DIR points. For Cloud Run
the extracted SDK must be baked into the Docker image -- see
docs/PHOTODNA_SETUP.md.

This wraps the SDK's own Python client library
(`<sdk>/clientlibrary/python/PhotoDna.EdgeHashGenerator`, a ctypes binding
that auto-selects the right native library for the platform, e.g.
libEdgeHashGenerator-arm64-macos.so.1.05 on Apple Silicon or
libEdgeHashGenerator.so.1.05 on x64 Linux/Cloud Run) IN-PROCESS -- one
library load per process, then each hash is a single native call. The
earlier design shelled out to the SDK's sample script per image; verified
against the real SDK, the client-library call is what that script does
internally, minus a Python+PIL startup per frame (a 60-frame video would
have paid that 60 times).

Image decoding follows the SDK sample's own mode mapping (GenerateEdgeHashes
.py `LoadImage`): RGB/RGBA/CMYK buffers pass through with the matching
pixel-layout flag, LA/PA/RGBa convert to RGBA, everything else converts to
RGB. Pillow (already a server dependency) does the decode; numpy is NOT
needed -- the binding accepts a plain bytes buffer.

Zero import-time side effects beyond stdlib/PIL imports, same contract as
csam_screening.py: env is read into module attributes that tests monkeypatch
directly, and the SDK library is only located/loaded on first use.
"""
import ctypes
import io
import logging
import os
import sys
import threading

from PIL import Image

logger = logging.getLogger(__name__)

PHOTODNA_SDK_DIR = os.getenv("PHOTODNA_SDK_DIR")

# Every Edge V2 base64 hash starts with base64("PDNA...") -- see the sample
# hash in the onboarding email. Verified against hashes generated by the real
# SDK (1.05.009) on 2026-11-18. Used as a sanity check on generated output.
EDGE_HASH_PREFIX = "UEROQQ"

_init_lock = threading.Lock()
# The native library is initialized with maxThreads=1 (matching the SDK's own
# sample); serialize hash calls rather than assume the handle is re-entrant
# under Flask's threaded request handling.
_hash_lock = threading.Lock()
_edgehash_module = None
_generator = None


class PhotoDNAHashError(Exception):
    """Edge hash generation failed (SDK missing/misconfigured, decode
    failure, or the native call errored). Message is always secret-free --
    hash generation is entirely local, no API key is involved."""


def _client_library_dir() -> str:
    """The SDK's `clientlibrary/` dir (native libs + python binding), or
    raises PhotoDNAHashError describing exactly what is missing."""
    if not PHOTODNA_SDK_DIR:
        raise PhotoDNAHashError(
            "PhotoDNA EdgeHash SDK not configured: set PHOTODNA_SDK_DIR to the "
            "extracted PhotoDNA.EdgeHashGeneration SDK root"
        )
    lib_dir = os.path.join(PHOTODNA_SDK_DIR, "clientlibrary")
    if not os.path.isdir(os.path.join(lib_dir, "python", "PhotoDna")):
        raise PhotoDNAHashError(
            f"no clientlibrary/python/PhotoDna under PHOTODNA_SDK_DIR={PHOTODNA_SDK_DIR} "
            "-- PHOTODNA_SDK_DIR must point at the extracted SDK root"
        )
    return lib_dir


def is_sdk_configured() -> bool:
    """Cheap preflight: True when the SDK layout is resolvable (does not load
    the native library). Lets callers (e.g. verify_photodna.py) give a precise
    setup message instead of a generic failure."""
    try:
        _client_library_dir()
        return True
    except PhotoDNAHashError:
        return False


def _get_generator():
    """Lazily import the SDK's python binding and initialize the native
    library once per process. Returns (EdgeHashGenerator module, generator
    instance). Raises PhotoDNAHashError on any setup failure."""
    global _edgehash_module, _generator
    if _generator is not None:
        return _edgehash_module, _generator
    with _init_lock:
        if _generator is not None:
            return _edgehash_module, _generator

        lib_dir = _client_library_dir()
        python_dir = os.path.join(lib_dir, "python")
        if python_dir not in sys.path:
            sys.path.append(python_dir)
        try:
            from PhotoDna import EdgeHashGenerator
        except Exception as e:
            raise PhotoDNAHashError(
                f"failed to import the SDK python binding from {python_dir}: "
                f"{type(e).__name__}: {e}"
            )

        try:
            # Same call shape as the SDK sample: library dir, maxThreads=1.
            # The binding probes `<lib_dir>/libEdgeHashGenerator-<platform>`
            # variants and raises FileNotFoundError if none load.
            generator = EdgeHashGenerator.PhotoDnaEdgeHashGenerator(lib_dir, 1, False)
            init_error = generator.GetErrorNumber()
            if init_error:
                raise PhotoDNAHashError(
                    f"EdgeHashGenerator init failed: {init_error} "
                    f"{generator.GetErrorString(init_error)}"
                )
        except PhotoDNAHashError:
            raise
        except FileNotFoundError as e:
            raise PhotoDNAHashError(f"native EdgeHashGenerator library not found: {e}")
        except Exception as e:
            raise PhotoDNAHashError(
                f"EdgeHashGenerator init failed: {type(e).__name__}: {e}"
            )

        logger.info(
            "[csam] PhotoDNA EdgeHashGenerator loaded (library version %s)",
            generator.LibraryVersionText(),
        )
        _edgehash_module, _generator = EdgeHashGenerator, generator
        return _edgehash_module, _generator


def _load_image(edgehash_module, image_bytes: bytes):
    """Decode image bytes and pick the matching SDK pixel-layout flag,
    mirroring the SDK sample's LoadImage mode mapping exactly."""
    options = edgehash_module.PhotoDnaOptions
    img = Image.open(io.BytesIO(image_bytes))
    img.load()
    if img.mode == "RGB":
        return img, options.Rgb
    if img.mode == "RGBA":
        return img, options.Rgba
    if img.mode == "CMYK":
        return img, options.Cmyk
    if img.mode in ("LA", "PA", "RGBa"):
        return img.convert("RGBA"), options.Rgba
    return img.convert("RGB"), options.Rgb


def generate_edge_hash(image_bytes: bytes, content_type: str = "image/jpeg") -> str:
    """Generate one PhotoDNA Edge Hash (Edge V2, base64 -- the MatchHash
    "PreHashV2" representation) for `image_bytes`.

    `content_type` is accepted for interface stability but unused: Pillow
    sniffs the actual format from the bytes.

    Raises PhotoDNAHashError on any failure -- callers in csam_screening map
    that to an "error" verdict, which CSAM_FAIL_MODE then arbitrates.
    """
    edgehash_module, generator = _get_generator()

    try:
        img, pixel_option = _load_image(edgehash_module, image_bytes)
    except Exception as e:
        raise PhotoDNAHashError(f"failed to decode image: {type(e).__name__}: {e}")

    try:
        width, height = img.size
        pixel_buffer = img.tobytes()
        hash_buffer = ctypes.create_string_buffer(
            b"", size=edgehash_module.HashSize.EdgeV2Base64.value
        )
        options = pixel_option | edgehash_module.PhotoDnaOptions.HashFormatEdgeV2Base64
        with _hash_lock:
            # Returns >= 0 on success; the binding itself raises
            # PhotoDnaException on a negative (error) result.
            generator.PhotoDnaEdgeHash(
                pixel_buffer, hash_buffer, width, height, 0, options
            )
    except Exception as e:
        raise PhotoDNAHashError(f"edge hash computation failed: {type(e).__name__}: {e}")

    edge_hash = hash_buffer.value.decode("ascii", errors="replace")
    if not edge_hash.startswith(EDGE_HASH_PREFIX):
        # Never ship a malformed value to the matching service -- a wrong
        # "clear" from garbage input must surface as an error instead.
        raise PhotoDNAHashError(
            "generated value does not look like an edge hash "
            f"(missing {EDGE_HASH_PREFIX} prefix; got {len(edge_hash)} chars)"
        )
    return edge_hash
